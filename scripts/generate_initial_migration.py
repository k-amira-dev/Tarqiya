"""Write migrations/versions/0001_initial_schema.py straight from the models, without a running database.

Normally you run `alembic revision --autogenerate`, which needs a live PostgreSQL. This script builds the
same operations from the model metadata so the first migration can be produced anywhere. Later schema
changes should use `alembic revision --autogenerate -m "..."` against the Docker database.

    python scripts/generate_initial_migration.py
"""
import re
from pathlib import Path

from alembic.autogenerate import render_python_code
from alembic.operations import ops
from sqlalchemy import Enum

import promoflow.db.models  # noqa: F401
from promoflow.db.base import Base

OUT = Path(__file__).resolve().parents[1] / "migrations" / "versions" / "0001_initial_schema.py"


def main() -> None:
    tables = Base.metadata.sorted_tables  # dependency order

    upgrade = ops.UpgradeOps(ops=[])
    for t in tables:
        upgrade.ops.append(ops.CreateTableOp.from_table(t))
        for ix in sorted(t.indexes, key=lambda i: i.name):
            upgrade.ops.append(ops.CreateIndexOp.from_index(ix))
    downgrade = ops.DowngradeOps(ops=[ops.DropTableOp.from_table(t) for t in reversed(tables)])

    render_opts = {"render_as_batch": False, "alembic_module_prefix": "op.", "sqlalchemy_module_prefix": "sa."}
    up = render_python_code(upgrade, **render_opts)
    down = render_python_code(downgrade, **render_opts)

    # Enum types are shared by several tables, so create each once up front (plain SQL, so the migration
    # also works in offline --sql mode) and stop create_table from creating them again.
    enums = {}
    for t in tables:
        for c in t.columns:
            if isinstance(c.type, Enum):
                enums[c.type.name] = list(c.type.enums)
    enum_pat = re.compile(r"sa\.Enum\((.*?), name='(\w+)'\)")
    up = enum_pat.sub(r"postgresql.ENUM(\1, name='\2', create_type=False)", up)
    down = enum_pat.sub(r"postgresql.ENUM(\1, name='\2', create_type=False)", down)
    up = up.replace("pgvector.sqlalchemy.vector.VECTOR", "pgvector.sqlalchemy.Vector")
    up = up.replace("astext_type=Text()", "astext_type=sa.Text()")
    down = down.replace("astext_type=Text()", "astext_type=sa.Text()")

    enum_lines = "\n".join(
        f"    op.execute(\"CREATE TYPE {name} AS ENUM ({', '.join(repr(v) for v in vals)})\")"
        for name, vals in sorted(enums.items())
    )
    drop_enum_lines = "\n".join(
        f"    op.execute(\"DROP TYPE IF EXISTS {name}\")" for name in sorted(enums)
    )

    body = f'''"""Initial PromoFlow schema ({len(tables)} tables, {len(enums)} enum types).

Generated by scripts/generate_initial_migration.py from promoflow/db/models.

Revision ID: 0001
Revises:
"""
import pgvector.sqlalchemy
import sqlalchemy as sa
from sqlalchemy import BigInteger, String, Text  # used unprefixed inside rendered ARRAY/JSONB types
from alembic import op
from sqlalchemy.dialects import postgresql

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None


def upgrade() -> None:
    op.execute("CREATE EXTENSION IF NOT EXISTS vector")
{enum_lines}
{_indent(up)}


def downgrade() -> None:
{_indent(down)}
{drop_enum_lines}
'''
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT} ({len(tables)} tables, {len(enums)} enum types)")


def _indent(code: str) -> str:
    # render_python_code wraps output in "# ### commands auto generated ..." comments at 4-space indent
    return "\n".join(line for line in code.splitlines() if line.strip() and "###" not in line)


if __name__ == "__main__":
    main()
